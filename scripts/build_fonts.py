"""Inline the downloaded woff2 fonts into site/css/fonts.css as data URIs (so file:// works in every browser).
Fonts: @fontsource Noto Sans Armenian 400/600/700, Noto Serif Armenian 700, Inter (latin) 400/600/700, JetBrains Mono (latin) 400/600/800 - all SIL OFL 1.1.
Run: python -P -X utf8 scripts/build_fonts.py
"""
import base64, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
F = os.path.join(ROOT, 'site', 'fonts')
ARM = 'U+0530-058F, U+FB13-FB17'
LAT = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
faces = [
    ('Noto Sans Armenian', 400, 'noto-sans-armenian-armenian-400-normal.woff2', ARM),
    ('Noto Sans Armenian', 600, 'noto-sans-armenian-armenian-600-normal.woff2', ARM),
    ('Noto Sans Armenian', 700, 'noto-sans-armenian-armenian-700-normal.woff2', ARM),
    ('Noto Serif Armenian', 700, 'noto-serif-armenian-armenian-700-normal.woff2', ARM),
    ('Inter', 400, 'inter-latin-400-normal.woff2', LAT),
    ('Inter', 600, 'inter-latin-600-normal.woff2', LAT),
    ('Inter', 700, 'inter-latin-700-normal.woff2', LAT),
    ('JetBrains Mono', 400, 'jetbrains-mono-latin-400-normal.woff2', LAT),
    ('JetBrains Mono', 600, 'jetbrains-mono-latin-600-normal.woff2', LAT),
    ('JetBrains Mono', 800, 'jetbrains-mono-latin-800-normal.woff2', LAT),
]
out = ['/* generated by scripts/build_fonts.py - SIL OFL 1.1 fonts from @fontsource */']
for fam, w, fn, rng in faces:
    b64 = base64.b64encode(open(os.path.join(F, fn), 'rb').read()).decode()
    out.append("@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:swap;src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:%s}" % (fam, w, b64, rng))
open(os.path.join(ROOT, 'site', 'css', 'fonts.css'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('fonts.css', os.path.getsize(os.path.join(ROOT, 'site', 'css', 'fonts.css')) // 1024, 'KB')
